"""Traced games for the step 3 design (14 Nov 2026 AEST; Luke: trace all the semi-finals plus two quarter-finals, quality games).
For each game: per lane, who played what, the step 1 model's pre-game expected gold edge at 10 (fitted only on games before that Worlds
day), and what really happened before 14:00 (gold edge at 10 and 15, kills by lane and who won them, first blood, plates by lane, first
dragon and grubs). These are the inputs the laning module will use and the outcomes it must reproduce across games.
Games: both semi-finals (GEN v IG, BLG v T1) and quarter-finals 1 (IG v TES) and 4 (T1 v KC).
usage (repo root): python -I research/laning/s5_traces.py   (writes research/laning/step3-traces.md)"""
import sys, os
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
import numpy as np, pandas as pd
from lib import config, data
from lib.runlog import Run, atomic_write
from lib.lane_model import pregame_preds
OUT = config.R / "laning" / "step3-traces.md"
SERIES = [("Semi-final", {"Gen.G", "Invictus Gaming"}), ("Semi-final", {"Bilibili Gaming", "T1"}),
          ("Quarter-final 1", {"Invictus Gaming", "Top Esports"}), ("Quarter-final 4", {"T1", "Karmine Corp"})]
LANES = {"top": ["top"], "jng": ["jng"], "mid": ["mid"], "bot": ["bot", "sup"]}
mm = lambda t: f"{int(t) // 60}:{int(t) % 60:02d}"
with Run("traces", inputs=[config.OE_CSV, config.TL_MATCH, config.TL_EVENTS]) as run:
    o = data.oe(["gameid", "league", "date", "game", "side", "position", "playername", "teamname", "champion", "golddiffat10", "golddiffat15", "result"]); data.check(o)
    K = o[(o.league == "WLDs") & (o.date >= "2026-11-03")]
    tm, ev, _ = data.timelines(); look = data.roles(o); PE = pregame_preds("y10").set_index(["gameid", "position"]).pred.to_dict()
    md = ["# Step 3 traced games: semi-finals and two quarter-finals", "",
          "_Generated by `research/laning/s5_traces.py` from the Oracle's Elixir file, the gol.gg timelines and the step 1 lane model "
          "(pre-game edges fitted only on games before each Worlds day). Gold edges are blue minus red. Do not edit by hand._", ""]
    n = 0
    for stage, teams in SERIES:
        gs = K[K.position == "team"].groupby("gameid").teamname.apply(set)
        ids = sorted([g for g, t in gs.items() if t == teams], key=lambda g: K[K.gameid == g].date.iloc[0])
        for gi, g in enumerate(ids, 1):
            P = K[(K.gameid == g) & K.position.isin(config.ROLES)].set_index(["side", "position"]); T = K[(K.gameid == g) & (K.position == "team")].set_index("side")
            blue, red = T.loc["Blue"].teamname, T.loc["Red"].teamname; win = blue if T.loc["Blue"].result == 1 else red
            md += [f"## {stage}, game {gi}: {blue} (blue) v {red} (red), {win} won (`{g}`, {K[K.gameid == g].date.iloc[0][:10]} UTC)", "",
                   "| Lane | Blue | Red | Expected edge at 10 (model) | Real at 10 | Real at 15 |", "|---|---|---|---|---|---|"]
            for L, rl in LANES.items():
                pb = ", ".join(f"{P.loc[('Blue', r)].playername} {P.loc[('Blue', r)].champion}" for r in rl); pr = ", ".join(f"{P.loc[('Red', r)].playername} {P.loc[('Red', r)].champion}" for r in rl)
                e = sum(PE.get((g, r), np.nan) for r in rl); r10 = sum(P.loc[("Blue", r)].golddiffat10 for r in rl); r15 = sum(P.loc[("Blue", r)].golddiffat15 for r in rl)
                md.append(f"| {L} | {pb} | {pr} | {e:+.0f} | {r10:+.0f} | {r15:+.0f} |")
            gid = tm[tm.gameid == g].gid
            if not len(gid): md += ["", "No timeline for this game.", ""]; continue
            e = ev[(ev.gid == gid.iloc[0]) & (ev.t < 840)].sort_values("t"); lines = []
            for x in e.itertuples():
                if x.type == "kill":
                    k = look.get((g, data.key(x.champ))); v = look.get((g, data.key(x.victim_champ)))
                    ast = [look[(g, data.key(a))][0] for a in str(x.assists).split("|") if isinstance(x.assists, str) and (g, data.key(a)) in look]
                    if k and v: lines.append(f"{mm(x.t)} {k[1]} {k[0]} kills {v[0]}" + (f" (with {', '.join(ast)})" if ast else " (solo)"))
                elif x.type in ("dragon", "grub", "herald", "tower"): lines.append(f"{mm(x.t)} {x.side} {x.type}" + (f" {x.detail}" if isinstance(x.detail, str) else ""))
            pl = e[e.type == "plate"].groupby(["side", "detail"]).size()
            md += ["", "**Before 14:00 (gol.gg timeline):** " + "; ".join(lines), "",
                   "**Plates before 14:00:** " + ", ".join(f"{s} {d.lower()} {c}" for (s, d), c in pl.items()), ""]
            n += 1
    run.result("games traced", n); atomic_write(OUT, "\n".join(md) + "\n"); print("games traced", n, "->", OUT)
